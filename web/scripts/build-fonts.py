"""
Self-hosted web fonts, trimmed to the ranges the site uses.

Sources are the Fontsource builds of the Google Fonts families (same files
Google serves, same unicode-range subsets). Each variable font is instanced
down to the axis ranges the site has always requested from Google, so every
glyph renders exactly as before while each file is smaller:

  Archivo         wght 400-900, wdth 100-125   (no style uses a width below 100)
  Inter           wght 400-600
  JetBrains Mono  wght 400-500
  Instrument Serif  static 400 roman + italic (copied unchanged)

Each Latin file is split in two, the way Google Fonts splits scripts: a
"core" face (ASCII, Latin-1 and common punctuation: everything the site's
copy uses) that pages preload, and a "rest" face with the remaining Latin
range that browsers fetch only if a page ever shows one of those characters.
Every glyph still renders in its real face; first paint needs less.

Output: web/src/assets/fonts/*.woff2 and fonts.css (imported by src/main.tsx).

Usage (from the repo root, once fonttools is available):
  python3 -m pip install fonttools brotli
  python3 web/scripts/build-fonts.py
"""
from __future__ import annotations

import re
import shutil
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = Path(__file__).resolve().parents[2]
PKGS = ROOT / "node_modules"
OUT = ROOT / "web" / "src" / "assets" / "fonts"

FAMILIES = [
    # (css file, axis limits, css overrides)
    ("@fontsource-variable/archivo/wdth.css", {"wght": (400, 900), "wdth": (100, 125)}, {"font-weight": "400 900", "font-stretch": "100% 125%"}),
    ("@fontsource-variable/inter/index.css", {"wght": (400, 600)}, {"font-weight": "400 600"}),
    ("@fontsource-variable/jetbrains-mono/index.css", {"wght": (400, 500)}, {"font-weight": "400 500"}),
    ("@fontsource/instrument-serif/400.css", None, {}),
    ("@fontsource/instrument-serif/400-italic.css", None, {}),
]

# Characters the first paint needs (unicode-range syntax): ASCII, no-break space,
# © ® · and the dashes, quotes, bullet and ellipsis the copy uses. Accented
# Latin letters live in the "rest" face and load only if a page shows one.
CORE = "U+0000-00A0,U+00A9,U+00AE,U+00B7,U+2013-2014,U+2018-201E,U+2022,U+2026,U+2039-203A,U+20AC,U+2122"


def parse_ranges(spec: str) -> set[int]:
    out: set[int] = set()
    for part in spec.replace(" ", "").split(","):
        lo, _, hi = part.removeprefix("U+").partition("-")
        out.update(range(int(lo, 16), int(hi or lo, 16) + 1))
    return out


def to_ranges(points: set[int]) -> str:
    pts = sorted(points)
    out, start, prev = [], None, None
    for p in pts + [None]:
        if start is None:
            start = prev = p
        elif p is not None and p == prev + 1:
            prev = p
        else:
            out.append(f"U+{start:04X}" + (f"-{prev:04X}" if prev != start else ""))
            start = prev = p
    return ",".join(out)


def subset_file(src: Path, dst: Path, codepoints: set[int]) -> None:
    opts = subset.Options()
    opts.layout_features = ["*"]
    opts.flavor = "woff2"
    opts.name_IDs = ["*"]
    opts.notdef_outline = True
    font = TTFont(src)
    sub = subset.Subsetter(opts)
    sub.populate(unicodes=codepoints)
    sub.subset(font)
    font.flavor = "woff2"
    font.save(dst)


FACE = re.compile(r"@font-face\s*{[^}]*}", re.S)
URL = re.compile(r"url\(\./files/([^)]+\.woff2)\)\s*format\('woff2(?:-variations)?'\)")


def instance(src: Path, dst: Path, limits: dict[str, tuple[int, int]] | None) -> None:
    if not limits:
        shutil.copyfile(src, dst)
        return
    font = TTFont(src)
    axes = {a.axisTag for a in font["fvar"].axes}
    partial = instancer.instantiateVariableFont(font, {k: v for k, v in limits.items() if k in axes}, updateFontNames=False)
    partial.flavor = "woff2"
    partial.save(dst)


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    css: list[str] = [
        "/* Generated by web/scripts/build-fonts.py. Do not edit by hand. */",
    ]
    before = after = 0
    for rel, limits, overrides in FAMILIES:
        sheet = PKGS / rel
        pkg_dir = sheet.parent
        for face in FACE.findall(sheet.read_text()):
            m = URL.search(face)
            if not m:
                continue
            name = m.group(1)
            src, dst = pkg_dir / "files" / name, OUT / name
            instance(src, dst, limits)
            before += src.stat().st_size
            after += dst.stat().st_size
            face = URL.sub(f"url(./{name}) format('woff2')", face)
            # Drop the woff fallback; every supported browser takes woff2.
            face = re.sub(r",\s*url\(\./files/[^)]+\.woff\)\s*format\('woff'\)", "", face)
            for prop, value in overrides.items():
                face = re.sub(rf"{prop}:\s*[^;]+;", f"{prop}: {value};", face)
            # Pages are pre-rendered, so text can paint before fonts arrive. The
            # fonts are preloaded with the HTML; `block` holds text for that short
            # moment instead of showing a fallback face and swapping (no flash of
            # the wrong font, no layout shift).
            face = re.sub(r"font-display:\s*[^;]+;", "font-display: block;", face)
            if "-latin-" not in name or "-latin-ext-" in name:
                css.append(face)
                continue
            # Split the Latin face into core (preloaded) and rest.
            latin = parse_ranges(re.search(r"unicode-range:\s*([^;]+);", face).group(1))
            core, rest = latin & parse_ranges(CORE), latin - parse_ranges(CORE)
            for part, points in (("core", core), ("rest", rest)):
                part_name = name.replace(".woff2", f"-{part}.woff2")
                subset_file(dst, OUT / part_name, points)
                after += (OUT / part_name).stat().st_size
                css.append(re.sub(r"unicode-range:\s*[^;]+;", f"unicode-range: {to_ranges(points)};", face.replace(f"./{name}", f"./{part_name}")))
            after -= dst.stat().st_size
            dst.unlink()
    (OUT / "fonts.css").write_text("\n".join(css) + "\n")
    print(f"{len(css) - 1} faces, {before / 1024:.0f} KB -> {after / 1024:.0f} KB")


if __name__ == "__main__":
    main()
