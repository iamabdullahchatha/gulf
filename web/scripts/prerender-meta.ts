/**
 * Writes a static HTML file per page with that page's title, description and
 * link-preview tags (Open Graph + Twitter/X), after `vite build`.
 *
 * Why: the site is a single-page app, and WhatsApp, LinkedIn, Facebook, X,
 * iMessage, Slack and Teams never run JavaScript when they build a link
 * preview — they read only the HTML the server sends. Without this, every
 * shared link previews as the homepage. Each file is dist/index.html with the
 * block between <!-- seo:start --> and <!-- seo:end --> replaced, written to
 * dist/<path>/index.html, which Vercel serves at /<path> before the SPA
 * fallback rewrite applies. The app itself is unchanged; it boots as usual.
 *
 * It also pre-renders each page's markup into <div id="root"> (from the SSR
 * bundle built by `vite build --ssr src/entry-server.tsx`), so the first
 * screen paints straight from the HTML and React hydrates it in place.
 * dist/app-shell.html keeps the empty root for unknown URLs (see the rewrite in
 * vercel.json), which render client-side.
 *
 * Runs on Node's native TypeScript support: `node scripts/prerender-meta.ts`.
 * Page data is loaded through Vite so the app's `@/` aliases resolve.
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { createHash } from 'node:crypto'
import { dirname, join, resolve } from 'node:path'
import { pathToFileURL } from 'node:url'
import { createServer } from 'vite'

type MetaInput = { title?: string; description?: string; path?: string }
type MetaModule = {
  buildMeta: (i: MetaInput) => unknown[]
  metaToHtml: (tags: unknown[], indent?: string) => string
}
type Page = { slug: string; title: string; description: string }

const TEMPLATE = 'dist/index.html'
const BLOCK = /<!-- seo:start -->[\s\S]*?<!-- seo:end -->/

if (!existsSync(TEMPLATE)) {
  console.error('[prerender-meta] dist/index.html not found. Run `vite build` first.')
  process.exit(1)
}
// Preload the four faces the first screen uses (Latin core subsets) so text paints
// in its real font straight from the HTML (fonts use font-display: block).
const FONT_FILES = [/^archivo-latin-wdth-normal-core-.+\.woff2$/, /^inter-latin-wght-normal-core-.+\.woff2$/, /^jetbrains-mono-latin-wght-normal-core-.+\.woff2$/, /^instrument-serif-latin-400-italic-core-.+\.woff2$/]
const assets = readdirSync('dist/assets')
const fontPreloads = FONT_FILES.map((re) => {
  const f = assets.find((a) => re.test(a))
  if (!f) throw new Error(`[prerender-meta] font not found: ${re}`)
  return `    <link rel="preload" as="font" type="font/woff2" href="/assets/${f}" crossorigin />`
}).join('\n')
const template = readFileSync(TEMPLATE, 'utf8').replace(/(<meta name="theme-color"[^>]*>\n)/, (m) => `${m}${fontPreloads}\n`)
const ROOT = '<div id="root"></div>'
if (!template.includes(ROOT)) {
  console.error('[prerender-meta] <div id="root"></div> missing from index.html.')
  process.exit(1)
}
const SSR = resolve('dist-ssr/entry-server.js')
if (!existsSync(SSR)) {
  console.error('[prerender-meta] dist-ssr/entry-server.js not found. Run `vite build --ssr src/entry-server.tsx --outDir dist-ssr` first.')
  process.exit(1)
}
const { render } = (await import(pathToFileURL(SSR).href)) as { render: (url: string) => string }
// Unknown URLs are rewritten here and render client-side.
writeFileSync('dist/app-shell.html', template)

// Pre-rendered pages paint from their HTML, so the app's JavaScript is started
// by a tiny boot script once the first frame is on screen, instead of being
// downloaded and evaluated before the first paint. The boot script then fetches
// the entry and its chunks in parallel. Its name carries a content hash, so the
// long-lived immutable cache on /assets stays safe.
const ENTRY = /\s*<script type="module" crossorigin src="(\/assets\/index-[\w-]+\.js)"><\/script>/
const PRELOADS = /\s*<link rel="modulepreload" crossorigin href="(\/assets\/[\w-]+\.js)">/g
const entry = template.match(ENTRY)?.[1]
const chunks = [...template.matchAll(PRELOADS)].map((m) => m[1])
if (!entry) {
  console.error('[prerender-meta] entry <script> not found in index.html.')
  process.exit(1)
}
const boot = `/* Generated by scripts/prerender-meta.ts: start the app after the first paint. */
let started = false
const start = () => {
  if (started) return
  started = true
  for (const href of ${JSON.stringify(chunks)}) {
    const l = document.createElement('link')
    l.rel = 'modulepreload'
    l.href = href
    document.head.append(l)
  }
  import(${JSON.stringify(entry)})
}
// Start once the page has actually painted (animation frames can run before
// anything is on screen). buffered: true also reports a paint that happened
// before this script ran.
try {
  new PerformanceObserver((list, obs) => {
    if (list.getEntries().some((e) => e.name === 'first-contentful-paint')) {
      obs.disconnect()
      setTimeout(start, 0)
    }
  }).observe({ type: 'paint', buffered: true })
} catch {
  requestAnimationFrame(() => requestAnimationFrame(start))
}
// Safety net: browsers without paint timing, background tabs.
setTimeout(start, 1500)
`
const bootFile = `assets/boot-${createHash('sha256').update(boot).digest('hex').slice(0, 10)}.js`
writeFileSync(join('dist', bootFile), boot)
const pageTemplate = template.replace(PRELOADS, '').replace(ENTRY, `\n    <script type="module" src="/${bootFile}"></script>`)
if (!BLOCK.test(template)) {
  console.error('[prerender-meta] seo markers missing from index.html.')
  process.exit(1)
}

const server = await createServer({ server: { middlewareMode: true }, appType: 'custom', logLevel: 'error', mode: 'production' })
try {
  const { buildMeta, metaToHtml } = (await server.ssrLoadModule('/src/lib/seo/meta.ts')) as MetaModule
  const { PAGE_META, sectorTitle } = (await server.ssrLoadModule('/src/config/site.ts')) as {
    PAGE_META: Record<string, { title?: string; description: string }>
    sectorTitle: (t: string) => string
  }
  const { SERVICES } = (await server.ssrLoadModule('/src/data/services.ts')) as { SERVICES: Page[] }
  const { INDUSTRIES } = (await server.ssrLoadModule('/src/data/industries.ts')) as { INDUSTRIES: Page[] }

  const list: (MetaInput & { path: string })[] = [
    ...Object.entries(PAGE_META).map(([path, m]) => ({ path, title: m.title, description: m.description })),
    ...SERVICES.map((s) => ({ path: `/services/${s.slug}`, title: s.title, description: s.description })),
    ...INDUSTRIES.map((i) => ({ path: `/industries/${i.slug}`, title: sectorTitle(i.title), description: i.description })),
  ]

  for (const page of list) {
    // A function replacement, so "$" in copy is never treated as a pattern.
    const body = render(page.path)
    const html = pageTemplate
      .replace(BLOCK, () => `<!-- seo:start -->\n${metaToHtml(buildMeta(page))}\n    <!-- seo:end -->`)
      .replace(ROOT, () => `<div id="root">${body}</div>`)
    const out = page.path === '/' ? TEMPLATE : join('dist', page.path, 'index.html')
    mkdirSync(dirname(out), { recursive: true })
    writeFileSync(out, html)
  }
  console.log(`[prerender-meta] Wrote pre-rendered HTML and link previews for ${list.length} pages`)
} finally {
  await server.close()
}
